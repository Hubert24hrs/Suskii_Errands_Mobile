#!/usr/bin/env bash
# Writes the two files the OpenNext Cloudflare adapter needs into one web app, for one deploy
# (ADR-0023): wrangler.jsonc (Worker name, assets, custom domains) and open-next.config.ts.
#
# They are generated in CI rather than committed so that apps/ stays Kimi's and the adapter's
# version is pinned in one place, web-deploy.yaml.
#
# Usage: write-cloudflare-config.sh <web-marketing|web-customer|web-admin> <zone>
#   zone is the apex domain the sites live on, e.g. suskiierrand.com
# Optional env (web-marketing only): ANDROID_APP_ID, ANDROID_CERT_SHA256, IOS_BUNDLE_ID,
#   APPLE_TEAM_ID, written as Worker vars for the .well-known files
set -euo pipefail

app="${1:?app name: web-marketing, web-customer or web-admin}"
zone="${2:?zone, e.g. suskiierrand.com}"

if ! [[ "$zone" =~ ^[a-z0-9-]+(\.[a-z0-9-]+)+$ ]]; then
  echo "zone must be a bare domain name, got '$zone'" >&2
  exit 1
fi

case "$app" in
  web-marketing) hosts=("$zone" "www.$zone") ;;
  web-customer) hosts=("app.$zone") ;;
  # Reachable only through Cloudflare Access; the Access application is set up for this host.
  web-admin) hosts=("admin.$zone") ;;
  *) echo "unknown app '$app'" >&2; exit 1 ;;
esac

dir="$(cd "$(dirname "$0")/../../apps/$app" && pwd)"

routes=""
for h in "${hosts[@]}"; do
  routes+="${routes:+, }{ \"pattern\": \"$h\", \"custom_domain\": true }"
done

# The .well-known routes read these per request (force-dynamic), and on Workers process.env holds
# the Worker's vars, not the build's environment. All four are public identifiers.
vars=""
if [ "$app" = web-marketing ]; then
  for name in ANDROID_APP_ID ANDROID_CERT_SHA256 IOS_BUNDLE_ID APPLE_TEAM_ID; do
    value="${!name:-}"
    [ -n "$value" ] || continue
    if ! [[ "$value" =~ ^[A-Za-z0-9.:,_-]+$ ]]; then
      echo "$name has characters a package id, team id or fingerprint list never has" >&2
      exit 1
    fi
    vars+="${vars:+, }\"$name\": \"$value\""
  done
fi

cat > "$dir/wrangler.jsonc" <<EOF
// generated by infra/web/write-cloudflare-config.sh; never committed
{
  "name": "suskii-$app",
  "main": ".open-next/worker.js",
  "compatibility_date": "2026-10-01",
  "compatibility_flags": ["nodejs_compat", "global_fetch_strictly_public"],
  "assets": { "directory": ".open-next/assets", "binding": "ASSETS" },
  "workers_dev": false,
  "preview_urls": false,
  "routes": [$routes],
  "vars": { $vars }
}
EOF

cat > "$dir/open-next.config.ts" <<'EOF'
// generated by infra/web/write-cloudflare-config.sh; never committed
import { defineCloudflareConfig } from '@opennextjs/cloudflare';

export default defineCloudflareConfig();
EOF

echo "Wrote wrangler.jsonc and open-next.config.ts for $app (${hosts[*]})"
