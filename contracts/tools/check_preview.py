#!/usr/bin/env python3
"""Keeps contracts/v1/error-codes honest against the code (contracts/README.md rule 3: no drift).

Errors (exit 1):
  * an ERR_ code raised by backend code is missing from error-codes.json, or not marked implemented
  * a code marked implemented is no longer raised anywhere
  * error-codes.json is malformed (duplicate codes, bad names, unknown status)
  * Meet copy uses a term docs/store/meet-copy-rules.md forbids: the Meet keys of every app_*.arb,
    the website's lib/i18n/meet.*.ts, and web-marketing files whose path names Meet (legal pages
    included), unless MEET_COPY_EXEMPT exempts that key or phrase
  * a MEET_COPY_EXEMPT entry without a key or phrase, or without a reason

Warnings (reported, never failing):
  * a code in packages/suskii_core/lib/src/errors.dart that the catalogue does not know, because
    that file is Kimi Code's
  * a MEET_COPY_EXEMPT entry that no longer exempts anything, as check_rls_matrix.py reports a
    stale waiver

Enums, the RPC catalogue and the rest of contracts/v1 are generated by generate_v1.py.

Usage:
  python contracts/tools/check_preview.py [repo_root]           check
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

CODE = re.compile(r"\bERR_[A-Z0-9_]*[A-Z0-9]\b")
STATUSES = {"implemented", "planned", "client"}
HERE = "contracts/tools/check_preview.py"

# docs/store/meet-copy-rules.md, whose "Forbidden terms" table must name exactly these (a unit test
# holds the two together). Gifts give status, not cash, and Cowries are spend-only (owner decision
# 2), so Meet copy must never read as paying for attention, company or meetings, which is what
# Play's sugar-dating clause describes. Whole words in any case, with or without spaces or hyphens
# between a term's words, and the common endings on its last: "withdrawals", "earners", "cashout"
# and "sponsorship" count.
MEET_COPY_TERMS = (
    "wallet", "earn", "earnings", "cash", "cash out", "withdraw", "get paid", "sponsor", "sugar",
    "generous", "allowance", "pay to chat", "gifts for dates", "discreet affairs",
)
# Forms of a term's word that an ending cannot reach. A plural last word is listed singular, and
# the ending adds the plural back.
MEET_COPY_FORMS: dict[str, tuple[str, ...]] = {
    "get": ("get", "gets", "getting", "got", "gotten"),
    "withdraw": ("withdraw", "withdrew"),
    "generous": ("generous", "generosity"),
    "gifts": ("gift", "gifts"),
    "dates": ("date",),
    "affairs": ("affair",),
}


def _term_pattern(term: str) -> str:
    forms = ("(?:" + "|".join(map(re.escape, MEET_COPY_FORMS.get(w, (w,)))) + ")" for w in term.split())
    return r"[\s-]*".join(forms)


MEET_COPY = re.compile(
    r"\b(?:"
    + "|".join(_term_pattern(t) for t in sorted(MEET_COPY_TERMS, key=len, reverse=True))
    + r")(?:al|ship|ly|ing|ed|er|able|n)?(?:s|es)?\b",
    re.IGNORECASE,
)
# Meet copy whose job is to say what Meet is not: a disclosure ("no cash value") or a guideline
# naming what it forbids. `<arb path>#<key>` exempts that key. `<ts or tsx path>#<phrase>` exempts
# that exact phrase, case-sensitive, wherever it occurs in that file, and nothing else on its line.
# Every entry carries the reason it was accepted (docs/store/meet-copy-rules.md, "Safety copy may
# name what it forbids").
MEET_COPY_EXEMPT: dict[str, str] = {}
# web-marketing pages that exist only because of Meet but whose path does not say so: the CSAE
# standards page (design §8.11).
MEET_ONLY_PAGES = ("child-safety",)


@dataclass(frozen=True)
class Finding:
    level: str  # "error" | "warning"
    message: str
    file: str | None = None

    def annotation(self) -> str:
        location = f" file={self.file}" if self.file else ""
        return f"::{self.level}{location}::{self.message}"


def backend_sources(root: Path) -> list[Path]:
    files = sorted((root / "supabase" / "migrations").glob("*.sql"))
    files += sorted(
        p for p in (root / "supabase" / "functions").rglob("*.ts") if not p.name.endswith("_test.ts")
    )
    files += sorted((root / "services").glob("*/src/**/*.py"))
    return files


def raised_codes(root: Path) -> dict[str, str]:
    """code -> first file (relative) that raises it."""
    found: dict[str, str] = {}
    for path in backend_sources(root):
        for code in CODE.findall(path.read_text(encoding="utf-8", errors="replace")):
            found.setdefault(code, path.relative_to(root).as_posix())
    return found


def client_codes(root: Path) -> set[str]:
    path = root / "packages" / "suskii_core" / "lib" / "src" / "errors.dart"
    return set(CODE.findall(path.read_text(encoding="utf-8"))) if path.exists() else set()


def _words(identifier: str) -> list[str]:
    return re.findall(r"[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])", identifier)


def is_meet_key(key: str) -> bool:
    """`meetTitle`, `errMeetupFull`, `notifMeetLikeTitle`; not `meetingPoint`."""
    return any(w.lower() in {"meet", "meetup", "meetups"} for w in _words(key))


def _meet_copy_files(root: Path) -> list[Path]:
    files = sorted((root / "apps" / "web-customer" / "src" / "lib" / "i18n").glob("meet.*.ts"))
    marketing = root / "apps" / "web-marketing" / "src"
    if marketing.is_dir():
        files += sorted(
            p for p in marketing.rglob("*")
            if p.suffix in {".ts", ".tsx"}
            and any(is_meet_key(part) or part.split(".")[0] in MEET_ONLY_PAGES
                    for part in p.relative_to(marketing).parts)
        )
    return files


def meet_copy_findings(root: Path) -> list[Finding]:
    findings: list[Finding] = []
    used: set[str] = set()

    def hits(text: str) -> list[str]:
        # Identifiers are camelCase, so `meetCashOut` reads as "meet Cash Out".
        return [m.group(0) for m in MEET_COPY.finditer(re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", text))]

    for arb in sorted((root / "packages" / "suskii_l10n" / "lib" / "l10n").glob("app_*.arb")):
        rel = arb.relative_to(root).as_posix()
        for key, value in json.loads(arb.read_text(encoding="utf-8")).items():
            if key.startswith("@") or not is_meet_key(key):
                continue
            terms = hits(f"{key}\n{value}")
            if terms and f"{rel}#{key}" in MEET_COPY_EXEMPT:
                used.add(f"{rel}#{key}")
                continue
            for term in terms:
                findings.append(Finding("error", f"Meet copy: {key} says {term!r}, which "
                                                 "docs/store/meet-copy-rules.md forbids", rel))

    for path in _meet_copy_files(root):
        rel = path.relative_to(root).as_posix()
        phrases = [where for where in MEET_COPY_EXEMPT if where.partition("#")[0] == rel]
        text = path.read_text(encoding="utf-8")
        # Comments are for developers; blank them but keep their newlines so line numbers hold.
        text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.DOTALL)
        for number, line in enumerate(text.splitlines(), 1):
            line = re.sub(r"(?<!:)//.*", "", line)
            for where in phrases:
                phrase = where.partition("#")[2]
                if phrase and phrase in line and hits(phrase):
                    used.add(where)
                    line = line.replace(phrase, " ")
            for term in hits(line):
                findings.append(Finding("error", f"Meet copy: line {number} says {term!r}, which "
                                                 "docs/store/meet-copy-rules.md forbids", rel))

    for where, reason in MEET_COPY_EXEMPT.items():
        if not where.partition("#")[2] or not reason.strip():
            findings.append(Finding("error", f"Meet copy exemption {where!r} needs the form "
                                             "`<path>#<key or phrase>` and a reason", HERE))
        elif where not in used:
            findings.append(Finding("warning", f"Meet copy exemption {where!r} no longer exempts "
                                               "anything; remove it", HERE))
    return findings


def check(root: Path) -> list[Finding]:
    preview = root / "contracts" / "v1" / "error-codes"
    findings: list[Finding] = []

    catalogue = json.loads((preview / "codes.json").read_text(encoding="utf-8"))
    entries = catalogue["codes"]
    seen: set[str] = set()
    for entry in entries:
        code = entry.get("code", "")
        if not re.fullmatch(r"ERR_[A-Z0-9_]*[A-Z0-9]", code):
            findings.append(Finding("error", f"malformed code name {code!r}", "contracts/v1/error-codes/codes.json"))
        if code in seen:
            findings.append(Finding("error", f"duplicate code {code}", "contracts/v1/error-codes/codes.json"))
        seen.add(code)
        if entry.get("status") not in STATUSES:
            findings.append(Finding("error", f"{code}: unknown status {entry.get('status')!r}", "contracts/v1/error-codes/codes.json"))

    status = {e["code"]: e.get("status") for e in entries}
    raised = raised_codes(root)
    for code, where in sorted(raised.items()):
        if code not in status:
            findings.append(Finding("error", f"{code} is raised but missing from error-codes.json", where))
        elif status[code] != "implemented":
            findings.append(Finding("error", f"{code} is raised but marked {status[code]}; mark it implemented", where))
    for code, st in sorted(status.items()):
        if st == "implemented" and code not in raised:
            findings.append(Finding("error", f"{code} is marked implemented but no backend code raises it",
                                    "contracts/v1/error-codes/codes.json"))

    # Enums moved to generate_v1.py with the rest of contracts/v1. Two tools generating the same
    # file is how the two copies end up disagreeing, which is the drift rule 3 forbids.

    for code in sorted(client_codes(root) - set(status)):
        findings.append(Finding("warning", f"{code} is used by the app but not in the preview catalogue "
                                           "(add it to error-codes.json or rename it in the app)",
                                "packages/suskii_core/lib/src/errors.dart"))

    findings += meet_copy_findings(root)
    return findings



def main(argv: list[str]) -> int:
    args = [a for a in argv[1:] if not a.startswith("--")]
    root = Path(args[0] if args else ".").resolve()
    if "--write" in argv:
        print(
            "::error::--write moved to contracts/tools/generate_v1.py with enums.json. "
            "Run: python contracts/tools/generate_v1.py . --write"
        )
        return 1
    findings = check(root)
    for finding in findings:
        print(finding.annotation())
    errors = sum(f.level == "error" for f in findings)
    print(f"check_preview: {errors} error(s), {len(findings) - errors} warning(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
